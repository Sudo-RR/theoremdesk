// Generate the installer's model list from tools.json:
//   theoremdesk-models.iss       size text and [UninstallDelete] entries
//   theoremdesk-models-code.iss  Pascal: TDModelCount, TDModelFile(I), TDModelUrl(I), TDModelSha(I), TDModelSize(I)
//
// Usage: node make_models_iss.js <tools.json> <platform> <output dir>

const fs = require('fs');
const path = require('path');

const [manifestPath, platform, outDir] = process.argv.slice(2);
const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'))[platform];
if (!manifest) {
	throw new Error(`no ${platform} in ${manifestPath}`);
}

// Sizes come from the download itself: Hugging Face reports them, and tools.json pins the hash.
const models = ['chat-model', 'embedding-model'].map((key) => {
	const m = manifest[key];
	if (!m || !m.url || !/^[0-9a-f]{64}$/.test(m.sha256) || !m.file) {
		throw new Error(`tools.json has no complete ${key} for ${platform}`);
	}
	if (!Number.isInteger(m.size) || m.size <= 0) {
		throw new Error(`tools.json has no size for ${key} (${platform}); add "size" in bytes`);
	}
	if (/['"{}]/.test(m.url + m.file)) {
		throw new Error(`${key}: unexpected characters in url or file`);
	}
	return m;
});

const gb = (models.reduce((s, m) => s + m.size, 0) / 1e9).toFixed(1);
const iss = [
	'; Generated by theoremdesk/installer/make_models_iss.js from theoremdesk/tools/tools.json. Do not edit.',
	`#define TDModelsSizeText "${gb} GB"`,
	'',
	'[UninstallDelete]',
	...models.flatMap((m) => [`Type: files; Name: "{#TDModelsDir}\\${m.file}"`, `Type: files; Name: "{#TDModelsDir}\\${m.file}.part"`]),
	'Type: dirifempty; Name: "{#TDModelsDir}"',
	'',
].join('\r\n');

const cases = (field, quote) => models.map((m, i) => `    ${i}: Result := ${quote ? `'${m[field]}'` : m[field]};`).join('\r\n');
const code = [
	'// Generated by theoremdesk/installer/make_models_iss.js from theoremdesk/tools/tools.json. Do not edit.',
	`const TDModelCount = ${models.length};`,
	'',
	...[
		['TDModelFile', 'file', 'String', true],
		['TDModelUrl', 'url', 'String', true],
		['TDModelSha', 'sha256', 'String', true],
		['TDModelSize', 'size', 'Int64', false],
	].flatMap(([name, field, type, quote]) => [`function ${name}(I: Integer): ${type};`, 'begin', '  case I of', cases(field, quote), '  end;', 'end;', '']),
].join('\r\n');

fs.writeFileSync(path.join(outDir, 'theoremdesk-models.iss'), iss);
fs.writeFileSync(path.join(outDir, 'theoremdesk-models-code.iss'), code);
console.log(`TheoremDesk: installer model list: ${models.map((m) => m.file).join(', ')} (${gb} GB)`);
