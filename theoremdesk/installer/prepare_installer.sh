#!/usr/bin/env bash
# Add TheoremDesk's second installer stage (the local AI models) to the
# Windows installer script, vscode/build/win32/code.iss:
#   - the model files are left out of the installer (it must stay under
#     Windows' 4 GB limit); setup installs them itself (theoremdesk.iss);
#   - the model list is generated from theoremdesk/tools/tools.json, so
#     the installer downloads exactly the pinned files.
#
# Usage: theoremdesk/installer/prepare_installer.sh <vscode source dir>
# theoremdesk/prepare.sh runs it during the build. Safe to run again.

set -euo pipefail

TD_DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )/.." && pwd )"
VSCODE_DIR="${1:?usage: prepare_installer.sh <vscode source dir>}"
WIN32="${VSCODE_DIR}/build/win32"
ISS="${WIN32}/code.iss"

[[ -f "${ISS}" ]] || { echo "TheoremDesk: no ${ISS}" >&2; exit 1; }

cp "${TD_DIR}/installer/theoremdesk.iss" "${TD_DIR}/installer/theoremdesk-code.iss" "${WIN32}/"

node "${TD_DIR}/installer/make_models_iss.js" "${TD_DIR}/tools/tools.json" win32-x64 "${WIN32}"

# The app's deepest relative file path, so setup can refuse an install folder
# that would push it past Windows' 260-character limit. Measured from the
# build when there is one (build_installer.sh runs after the build), else a
# safe guess.
APP_DIR="$( dirname "${VSCODE_DIR}" )/VSCode-win32-x64"
LONGEST=200
if [[ -d "${APP_DIR}" ]]; then
  LONGEST="$( cd "${APP_DIR}" && find . -type f | awk '{ n = length($0) - 2; if (n > m) m = n } END { print m + 0 }' )"
fi
printf '; Generated by theoremdesk/installer/prepare_installer.sh. Do not edit.\r\n#define TDLongestPath %s\r\n' "${LONGEST}" > "${WIN32}/theoremdesk-paths.iss"
echo "TheoremDesk: the app's deepest file path is ${LONGEST} characters"

node - "${ISS}" << 'EOF'
const fs = require('fs');
const file = process.argv[2];
let iss = fs.readFileSync(file, 'utf8');
const before = iss;
// 1. Leave the models out of the installer's files.
const excludes = '\\resources\\tools\\ai\\models,\\resources\\tools\\ai\\models\\*';
iss = iss.replace(/^(Source: "\*"; Excludes: ")([^"]*)(")/m, (m, a, list, b) => (list.includes('\\resources\\tools\\ai\\models') ? m : `${a}${list},${excludes}${b}`));
if (!iss.includes(excludes)) {
	throw new Error('TheoremDesk: could not find the Source: "*" line in code.iss to exclude the models');
}
// 2. The declarations before [Code], the code at the end.
if (!iss.includes('#include "theoremdesk.iss"')) {
	iss = iss.replace(/^\[Code\]$/m, '#include "theoremdesk.iss"\n\n[Code]');
}
if (!iss.includes('#include "theoremdesk-code.iss"')) {
	iss = iss.trimEnd() + '\n\n#include "theoremdesk-code.iss"\n';
}
if (!iss.includes('#include "theoremdesk.iss"')) {
	throw new Error('TheoremDesk: could not find [Code] in code.iss');
}
if (iss !== before) {
	fs.writeFileSync(file, iss);
}
EOF

echo "TheoremDesk: installer stage 2 (local AI models) added to ${ISS}"
